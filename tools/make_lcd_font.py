# make_lcd_font.py - src/lcd_font.h: the characters of the MT-32 module display as a 5 x 9 dot matrix (ASCII 32 .. 126).
# Source: the X11 bitmap font "Misc Fixed 6x10" (a public domain font: "Public domain font. Share and enjoy."): capitals are 5 x 7 dots like on the
# LCD of the real device, the descenders (g j p q y ...) go two dots below the baseline.
# usage: python3 tools/make_lcd_font.py [/usr/share/fonts/misc/6x10.pcf.gz] > src/lcd_font.h        (needs Pillow)
import sys, gzip, io, tempfile, os
from PIL import Image, ImageDraw, ImageFont
import numpy as np
path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/misc/6x10.pcf.gz'
raw = gzip.open(path).read() if path.endswith('.gz') else open(path, 'rb').read()
tmp = tempfile.NamedTemporaryFile(suffix='.pcf', delete=False); tmp.write(raw); tmp.close()
f = ImageFont.truetype(tmp.name, 10); os.unlink(tmp.name)
rows = []
for c in range(32, 127):
    im = Image.new('L', (8, 16), 0); ImageDraw.Draw(im).text((1, 11), chr(c), font=f, fill=255, anchor='ls')     # the baseline at row 11
    a = np.asarray(im) > 127
    sub = a[4:13, 1:6]                      # rows 4 .. 12 = 9 rows (capitals at rows 4 .. 10, descenders to 12), 5 columns
    if a[:4].any() or a[13:].any() or a[:, 6:].any() or a[:, :1].any(): sys.stderr.write('glyph %r does not fit: ignored parts\n' % chr(c))
    rows.append([sum(1 << (4 - x) for x in range(5) if sub[y, x]) for y in range(9)])
print('/* SPDX-License-Identifier: GPL-3.0-or-later */')
print('/* The characters of the display of the MT-32 module as a 5 x 9 dot matrix (ASCII 32 .. 126), generated by tools/make_lcd_font.py from the public domain font Misc Fixed 6x10:')
print(' * one byte per row, bit 4 = the left dot; capitals use rows 0 .. 6, descenders rows 7 and 8. */')
print('static const unsigned char lcd_font[95][9] = {')
for c, r in zip(range(32, 127), rows):
    print('    {%s},   /* %s */' % (','.join('0x%02X' % v for v in r), chr(c).replace('\\', '\\\\').replace('*/', '* /') if chr(c) != '\\' else 'backslash'))
print('};')
